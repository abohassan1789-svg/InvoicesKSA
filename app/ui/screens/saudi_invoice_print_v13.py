"""«النموذج الرابع عشر» — an exact replica of the ZATCA tax-invoice layout the
user supplied (``310731242800003_...INV-2026-63813.pdf`` — a «موسم الفاكهة /
Fruit Season» invoice generated by an Odoo-style ZATCA renderer).

Like the fixed-brand templates (المتكاملة/الإسناد الماسي/اقاسيم/الخطوط السعودية),
the seller identity + logo are HARDCODED to the source PDF's «موسم الفاكهة / Fruit
Season» (user request 2026-09-16: «نفس اللوجو بدون أي تغيير وبيانات البائع ثابتة
زي ملف الـ PDF») and never read the selected company — see the ``_FS_*`` constants
and :func:`_fixed_seller_block`. Everything else stays live from the shared
``data`` dict: the customer block, the 9-column items table, the totals box, the
amount-in-words and the QR. It is offered on the Phase-2 (المرحلة الثانية) invoice
screen, so its QR carries the full signed Phase-2 payload (``data["qr_payload"]``),
exactly like النماذج الأول→الحادي عشر.

Design, captured 1:1 from the reference PDF (measured with PyMuPDF):
* Title «Tax Invoice» + the invoice number are brand orange ``#AF6018``.
* The 5 meta labels (Invoice/Due/Supply Date, Source, Salesman) are muted-green
  ``#99AF9B``; their values are ink ``#111827``. Per the user's instruction, all
  five values print the invoice's own date (our system does not store a separate
  due/supply date, source or salesman).
* Items table columns (LTR): LOT/SERIAL · DESCRIPTION · QUANTITY · PRICE WITHOUT
  TAX · PRICE TAX AMOUNT · UNIT PRICE · SUBTOTAL · VAT AMOUNT · TOTAL (VAT INCL.).
  The three per-unit columns are derived from the line's own amounts:
  price-without-tax = before/qty, price-tax-amount = vat_amount/qty,
  unit-price = total/qty (VAT-inclusive), matching how the reference was made.
* Totals box (flush right): Untaxed Amount · VAT Total Amount · **Total** (orange).
* Amount in words prints in English («Three Hundred Riyal»), as the reference did.
* Footer (repeats at every page bottom via the <tfoot> spacer trick): seller VAT
  on the left, «ZATCA: <issue timestamp>, Page 1 / 1» on the right.
"""

from __future__ import annotations

import datetime
import html
from decimal import Decimal, InvalidOperation
from typing import Any

from app.ui.screens.saudi_invoice_print import (
    QR_PRINT_PX,
    _asset_data_uri,
    qr_vector_data_uri,
    with_print_descriptions,
)

# ---------------------------------------------------------------------------
# Design tokens — measured from the reference PDF.
# ---------------------------------------------------------------------------
_ORANGE = "#AF6018"          # «Tax Invoice» / invoice number / «Total»
_LABEL = "#99AF9B"           # the muted-green meta labels
_INK = "#111827"             # values / body text
_MUTED = "#5F636F"           # amount-in-words value + footer ZATCA line
_BORDER = "#c9ced4"          # thin light-grey table / totals-box grid
_FONTS = "'Tajawal','Cairo','Segoe UI','Tahoma','Arial',sans-serif"

_SHEET_W = 816               # Letter sheet, matching _page_layout() and all templates
_SHEET_H = 1056

# ---------------------------------------------------------------------------
# FIXED BRAND (user request 2026-09-16: «نفس اللوجو بدون أي تغيير وبيانات البائع
# ثابتة زي ملف الـ PDF»). Like المتكاملة/الإسناد الماسي/اقاسيم/الخطوط السعودية,
# the seller identity + logo are hardcoded to the source PDF's «موسم الفاكهة /
# Fruit Season» and NEVER read the selected company. Everything else (customer,
# items, totals, QR) stays live from ``data``.
# ---------------------------------------------------------------------------
_FS_LOGO_ASSET = "mawsim_fruitseason_logo.png"   # extracted 1:1 from the source PDF
_FS_NAME = "شركة موسم الفاكهة للتجارة - التجزئة"
_FS_ADDRESS_LINES = (
    "طريق عمر بن عبد العزيز",
    "حي الربوة",
    "الرياض RUH 12816",
    "5010 7077",
    "Saudi Arabia",
)
_FS_VAT = "310731242800003"
_FS_CR = "1010658115"
_FS_SALESMAN = "Ibrahim Alabdulla"   # fixed salesman name (from the source PDF)


def _dec(value: Any) -> Decimal:
    """Best-effort Decimal, ``0`` on anything unparseable."""
    try:
        return Decimal(str(value))
    except (InvalidOperation, TypeError, ValueError):
        return Decimal("0")


def _sr(value: Any) -> str:
    """Money with a trailing « SR », e.g. ``104.35 SR`` (reference format)."""
    return f"{_dec(value):,.2f} SR"


def _per_unit(total_value: Any, qty: Any) -> str:
    """A per-unit amount = ``total_value / qty`` with « SR », qty-0 safe."""
    q = _dec(qty)
    if q == 0:
        return _sr(total_value)
    return _sr(_dec(total_value) / q)


def _qty2(value: Any) -> str:
    """Quantity with two decimals like the reference (``2.00``)."""
    return f"{_dec(value):,.2f}"


def amount_in_words_en(total: Any) -> str:
    """Spell a SAR amount in English words, e.g. ``Three Hundred Riyal``."""
    amount = _dec(total).quantize(Decimal("0.01"))
    riyals = int(amount)
    halalas = int((amount - riyals) * 100)
    try:
        from num2words import num2words

        riyal_words = num2words(riyals, lang="en").title()
    except Exception:  # noqa: BLE001 - fall back to digits if lib misbehaves
        riyal_words = str(riyals)
    text = f"{riyal_words} Riyal"
    if halalas:
        try:
            from num2words import num2words

            halala_words = num2words(halalas, lang="en").title()
        except Exception:  # noqa: BLE001
            halala_words = str(halalas)
        text += f" and {halala_words} Halala"
    return text


def _fixed_seller_block() -> str:
    """The LEFT header block — the fixed «موسم الفاكهة / Fruit Season» seller,
    hardcoded from the source PDF (name, multi-line address, VAT, CR)."""
    address_html = "".join(
        f'<div style="margin-top:2px; line-height:1.5;" dir="rtl">{html.escape(line)}</div>'
        for line in _FS_ADDRESS_LINES
    )
    return f"""
    <div style="text-align:left; font-size:12.5px; color:{_INK};">
      <div style="font-weight:800; font-size:13px;" dir="rtl">{html.escape(_FS_NAME)}</div>
      {address_html}
      <div style="margin-top:8px;"><span style="font-weight:800;">VAT:</span> {html.escape(_FS_VAT)}</div>
      <div style="margin-top:2px;"><span style="font-weight:800;">CR:</span> {html.escape(_FS_CR)}</div>
    </div>"""


def _party_block(party: dict[str, Any], *, align: str) -> str:
    """The customer header block (right side).

    Lines, top to bottom (user's layout, 2026-09-24): name, address, the
    commercial-registration number on its own (NO «CR:» / «السجل التجاري»
    label), a fixed «Saudi Arabia» line, then «VAT:»."""
    name = html.escape(str(party.get("name") or ""))
    address = html.escape(str(party.get("address") or ""))
    vat = html.escape(str(party.get("vat") or ""))
    cr = html.escape(str(party.get("cr") or ""))
    address_html = (
        f'<div style="margin-top:2px; line-height:1.5;" dir="rtl">{address}</div>'
        if address
        else ""
    )
    cr_html = f'<div style="margin-top:2px;">{cr}</div>' if cr else ""
    vat_html = (
        f'<div style="margin-top:8px;"><span style="font-weight:800;">VAT:</span> {vat}</div>'
        if vat
        else ""
    )
    return f"""
    <div style="text-align:{align}; font-size:12.5px; color:{_INK};">
      <div style="font-weight:800; font-size:13px;" dir="rtl">{name}</div>
      {address_html}
      {cr_html}
      <div style="margin-top:2px;">Saudi Arabia</div>
      {vat_html}
    </div>"""


def _meta_cell(label: str, value: str) -> str:
    """One column of the 5-up meta strip (green label over ink value)."""
    return f"""
      <div style="text-align:left;">
        <div style="font-size:11px; font-weight:700; color:{_LABEL};">{label}</div>
        <div style="font-size:12.5px; color:{_INK}; margin-top:3px;">{value}</div>
      </div>"""


def _th(text: str, width: str, align: str = "right") -> str:
    return (
        f'<th style="width:{width}; border:1px solid {_BORDER}; padding:6px 5px; '
        f'text-align:{align}; vertical-align:top; font-size:9.5px; font-weight:700; '
        f'color:{_INK};">{text}</th>'
    )


def _item_rows(lines: list[dict[str, Any]], show_desc: bool = False) -> str:
    if not lines:
        return (
            f'<tr><td colspan="{10 if show_desc else 9}" style="border:1px solid {_BORDER}; text-align:center; '
            f'padding:18px 6px; color:#999; font-size:11px;" dir="rtl">لا توجد أصناف</td></tr>'
        )
    cell = f'border:1px solid {_BORDER}; padding:8px 5px; font-size:10px; color:{_INK}; vertical-align:middle;'
    rows: list[str] = []
    for line in lines:
        code = html.escape(str(line.get("code") or ""))
        name = html.escape(str(line.get("name") or ""))
        unit = html.escape(str(line.get("unit") or ""))
        qty = line.get("qty")
        before = line.get("before")
        vat_amount = line.get("vat_amount")
        total = line.get("total")
        code_html = f' <span style="color:{_MUTED};">[{code}]</span>' if code else ""
        qty_txt = f"{_qty2(qty)} {unit}".strip()
        # «ITEM DESCRIPTION» column (toggle «إظهار وصف الصنف»), right after the name.
        desc_td = (
            f'<td style="{cell} text-align:right;" dir="rtl">{html.escape(line.get("print_description") or "")}</td>'
            if show_desc
            else ""
        )
        rows.append(f"""
      <tr>
        <td style="{cell} text-align:center;">-</td>
        <td style="{cell} text-align:right;" dir="rtl">{name}{code_html}</td>{desc_td}
        <td style="{cell} text-align:left;">{qty_txt}</td>
        <td style="{cell} text-align:right;">{_per_unit(before, qty)}</td>
        <td style="{cell} text-align:right;">{_per_unit(vat_amount, qty)}</td>
        <td style="{cell} text-align:right;">{_per_unit(total, qty)}</td>
        <td style="{cell} text-align:right;">{_sr(before)}</td>
        <td style="{cell} text-align:right;">{_sr(vat_amount)}</td>
        <td style="{cell} text-align:right;">{_sr(total)}</td>
      </tr>""")
    return "".join(rows)


