"""Generate ``barakah_company.sql`` — adds «شركة زيادة البركة التجارية» (the seller
of the النموذج الثاني والعشرون reference PDF) to the companies master, stamp
included. Run from the repo root: ``python tools/barakah_company/gen_sql.py``.

``stamp.png`` is the seal lifted from the PDF (its embedded 1254×1254 RGBA
image, scaled to 400px and palette-reduced so the SQL stays small).
"""

from __future__ import annotations

import base64
from pathlib import Path

HERE = Path(__file__).resolve().parent

COMPANY = {
    "name_ar": "شركة زيادة البركة التجارية",
    "commercial_registration": "7009631370",
    "vat_number": "311369317100003",
    "address_ar": "جدة - العزيزية - البلدية - 23334",
}


def _q(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


def build_sql() -> str:
    c = COMPANY
    stamp = base64.b64encode((HERE / "stamp.png").read_bytes()).decode("ascii")
    stamp_lines = "\n".join(f"    '{stamp[i:i + 100]}'" for i in range(0, len(stamp), 100))
    return f"""-- «شركة زيادة البركة التجارية» → companies (with its stamp).
-- Generated by tools/barakah_company/gen_sql.py — do not edit by hand.
-- Safe to run more than once: the company is matched by VAT number or CR and
-- inserted only if missing; an existing row only gets the stamp if it has none.

-- The file is UTF-8; say so explicitly so psql on Windows (console code
-- page, e.g. WIN1256) does not mangle the Arabic text.
SET client_encoding = 'UTF8';

BEGIN;

INSERT INTO companies (name_ar, commercial_registration, vat_number, address_ar)
SELECT {_q(c["name_ar"])}, {_q(c["commercial_registration"])}, {_q(c["vat_number"])},
       {_q(c["address_ar"])}
WHERE NOT EXISTS (
    SELECT 1 FROM companies
    WHERE vat_number = {_q(c["vat_number"])} OR commercial_registration = {_q(c["commercial_registration"])}
);

UPDATE companies
SET stamp = decode(
{stamp_lines}
    , 'base64'),
    stamp_mime = 'image/png'
WHERE vat_number = {_q(c["vat_number"])} AND stamp IS NULL;

COMMIT;
"""


if __name__ == "__main__":
    out = HERE / "barakah_company.sql"
    out.write_text(build_sql(), encoding="utf-8")
    print(f"wrote {out}")
