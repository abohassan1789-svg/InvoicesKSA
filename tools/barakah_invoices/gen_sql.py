"""Generate ``barakah_invoices.sql``: the 10 «زيادة البركة» sales invoices and
8 receipt vouchers for شركة النقيب للإنارة الحديثة, as rows in the app's own
tables (invoices as credit drafts, so the customer statement nets to zero).

Line amounts are computed with the app's own rules
(``SaudiSalesInvoiceService.compute_line_amounts`` / ``compute_totals``, copied
here as plain Decimal math so the script needs no app imports), and each
invoice's totals are asserted against the Excel figures before anything is
written. ``alloc.json`` holds the free-text lines of each invoice, picked from the
electrical items list by ``alloc.py``.

Run:  python tools/barakah_invoices/gen_sql.py
"""

from __future__ import annotations

import json
import os
from decimal import ROUND_HALF_UP, Decimal

HERE = os.path.dirname(os.path.abspath(__file__))

# Seeded by tools/barakah_company/barakah_company.sql (must run first).
SELLER = {
    "name_ar": "شركة زيادة البركة التجارية",
    "vat": "311369317100003",
}
CUSTOMER = {
    "name": "شركة النقيب للإنارة الحديثة",
    "vat": "311103749200003",
    "cr": "7011567356",
    "address": "جدة - حي البلد - شارع بامحرز - مبنى 2779 - الرقم الفرعي 6234 - 22233",
}
# (invoice number, issue date, pre-tax amount) — exactly as in the Excel sheet.
INVOICES = [
    ("736", "2026-07-06", 26800),
    ("753", "2026-07-19", 23400),
    ("769", "2026-07-28", 29000),
    ("785", "2026-08-03", 18000),
    ("802", "2026-08-15", 23500),
    ("817", "2026-08-25", 24000),
    ("829", "2026-09-01", 27400),
    ("840", "2026-09-08", 30400),
    ("861", "2026-09-17", 21000),
    ("877", "2026-09-30", 27800),
]
# (voucher number, date, amount) — the «السندات» block of the same sheet.
VOUCHERS = [
    ("113", "2026-07-11", 30000),
    ("119", "2026-07-22", 25000),
    ("127", "2026-08-11", 40000),
    ("136", "2026-08-20", 30000),
    ("144", "2026-09-04", 40000),
    ("157", "2026-09-28", 35000),
    ("164", "2026-10-06", 45000),
    ("171", "2026-10-11", 43995),
]
VOUCHER_PAYMENT_TYPE = "bank_transfer"
GRAND_TOTAL = Decimal("288995.00")
VAT_RATE = Decimal("15.00")
CENT = Decimal("0.01")


def money(value: Decimal) -> Decimal:
    return value.quantize(CENT, rounding=ROUND_HALF_UP)


def lit(value: object) -> str:
    """SQL literal (strings quoted and escaped; None -> NULL)."""
    if value is None:
        return "NULL"
    if isinstance(value, Decimal):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def voucher_purposes(totals: list[Decimal]) -> list[str]:
    """«وذلك قيمة» text of each voucher: the invoices it settles, oldest first."""
    due = [[number, total] for (number, _d, _a), total in zip(INVOICES, totals)]
    purposes = []
    for _number, _day, amount in VOUCHERS:
        left, full, part = Decimal(amount), [], None
        while left > 0:
            inv = due[0]
            if inv[1] <= left:
                left -= inv[1]
                full.append(inv[0])
                due.pop(0)
            else:
                inv[1] -= left
                part, left = inv[0], Decimal(0)
        text = []
        if full:
            text.append(("سداد الفواتير " if len(full) > 1 else "سداد الفاتورة ") + " و".join(full))
        if part:
            text.append(f"دفعة من الفاتورة {part}")
        purposes.append(" و".join(text))
    assert not due
    return purposes


def main() -> None:
    alloc = json.load(open(os.path.join(HERE, "alloc.json"), encoding="utf-8"))
    numbers = ", ".join(lit(n) for n, _d, _a in INVOICES)
    vouchers = ", ".join(lit(n) for n, _d, _a in VOUCHERS)
    vat = lit(SELLER["vat"])
    out: list[str] = [
        "-- «زيادة البركة» → شركة النقيب للإنارة الحديثة: 10 sales invoices (credit",
        "-- drafts) and the 8 receipt vouchers that pay them off (288,995.00).",
        "-- Generated by tools/barakah_invoices/gen_sql.py — do not edit by hand.",
        "-- Run tools/barakah_company/barakah_company.sql first (it adds the seller).",
        "-- Safe to run once: the whole script is one transaction and it stops",
        "-- without changing anything if any of these invoice numbers already exists",
        "-- for this seller, or any of these voucher numbers already exists.",
        "",
        "-- The file is UTF-8; say so explicitly so psql on Windows (console code",
        "-- page, e.g. WIN1256) does not mangle the Arabic text.",
        "SET client_encoding = 'UTF8';",
        "",
        "BEGIN;",
        "",
        "DO $$",
        "BEGIN",
        f"    IF NOT EXISTS (SELECT 1 FROM companies WHERE vat_number = {vat}) THEN",
        "        RAISE EXCEPTION 'زيادة البركة: company not found; run tools/barakah_company/barakah_company.sql first.';",
        "    END IF;",
        "    IF EXISTS (",
        "        SELECT 1 FROM sales_invoices i",
        "        JOIN companies c ON c.id = i.seller_company_id",
        f"        WHERE c.vat_number = {vat} AND i.invoice_number IN ({numbers})",
        "    ) THEN",
        "        RAISE EXCEPTION 'زيادة البركة: invoice numbers 736-877 already exist; nothing was imported.';",
        "    END IF;",
        f"    IF EXISTS (SELECT 1 FROM receipt_vouchers WHERE voucher_number IN ({vouchers})) THEN",
        "        RAISE EXCEPTION 'زيادة البركة: voucher numbers 113-171 already exist; nothing was imported.';",
        "    END IF;",
        "END $$;",
        "",
        "-- Customer (matched by VAT number; inserted only if missing).",
        "INSERT INTO customers (customer_name, vat_number, cr, address)",
        f"SELECT {lit(CUSTOMER['name'])}, {lit(CUSTOMER['vat'])}, {lit(CUSTOMER['cr'])}, {lit(CUSTOMER['address'])}",
        f"WHERE NOT EXISTS (SELECT 1 FROM customers WHERE vat_number = {lit(CUSTOMER['vat'])});",
        "",
    ]
    seller_id = f"(SELECT id FROM companies WHERE vat_number = {vat})"
    seller_en = f"(SELECT name_en FROM companies WHERE vat_number = {vat})"
    customer_id = (
        f"(SELECT MIN(customer_id) FROM customers WHERE vat_number = {lit(CUSTOMER['vat'])})"
    )
    grand = Decimal(0)
    totals: list[Decimal] = []
    for (number, day, amount), lines in zip(INVOICES, alloc):
        rows = []
        subtotal = vat_total = Decimal(0)
        for ln in lines:
            qty, price = Decimal(ln["qty"]), Decimal(ln["price"])
            before = money(qty * price)
            line_vat = money(before * VAT_RATE / 100)
            subtotal += before
            vat_total += line_vat
            rows.append((ln["code"], ln["name"], qty, price, before, line_vat, before + line_vat))
        subtotal, vat_total = money(subtotal), money(vat_total)
        total = subtotal + vat_total
        assert subtotal == amount and vat_total == money(Decimal(amount) * VAT_RATE / 100), number
        grand += total
        totals.append(total)
        values = ",\n".join(
            f"    ({n}, {lit(code)}, {lit(name)}, {qty}, {price}, {before}, {line_vat}, {tot})"
            for n, (code, name, qty, price, before, line_vat, tot) in enumerate(rows, start=1)
        )
        out += [
            f"-- Invoice {number} — {day} — {subtotal} + VAT {vat_total} = {total}",
            "WITH inv AS (",
            "    INSERT INTO sales_invoices (",
            "        invoice_number, issue_datetime, seller_company_id, seller_name_ar_snapshot,",
            "        seller_name_en_snapshot, seller_vat_number_snapshot, customer_id,",
            "        customer_name_snapshot, customer_vat_number_snapshot, customer_address_snapshot,",
            "        payment_type, invoice_currency_code, tax_currency_code, subtotal_before_vat,",
            "        invoice_discount_rate, invoice_discount_amount, subtotal_after_discount,",
            "        vat_total, total_including_vat, document_status)",
            f"    VALUES ({lit(number)}, {lit(day + ' 12:00:00+03')}, {seller_id},",
            f"        {lit(SELLER['name_ar'])}, {seller_en}, {vat},",
            f"        {customer_id}, {lit(CUSTOMER['name'])}, {lit(CUSTOMER['vat'])}, {lit(CUSTOMER['address'])},",
            f"        'credit', 'SAR', 'SAR', {subtotal}, 0, 0, {subtotal}, {vat_total}, {total}, 'draft')",
            "    RETURNING id, invoice_number, seller_company_id",
            "), lines AS (",
            "    INSERT INTO sales_invoice_lines (",
            "        invoice_id, line_number, product_id, product_code_snapshot, product_name_snapshot,",
            "        unit_code, quantity, unit_price, line_amount_before_vat, vat_category_code,",
            "        vat_rate, vat_amount, line_total_including_vat)",
            "    SELECT inv.id, v.n, NULL, v.code, v.name, 'PCE', v.qty, v.price, v.before, 'S',",
            "           15.00, v.vat, v.total",
            "    FROM inv, (VALUES",
            values,
            "    ) AS v(n, code, name, qty, price, before, vat, total)",
            "    RETURNING 1",
            ")",
            "INSERT INTO sales_invoice_audit_logs (",
            "    invoice_id, invoice_number_snapshot, seller_company_id_snapshot, action,",
            "    old_status, new_status, details)",
            "SELECT inv.id, inv.invoice_number, inv.seller_company_id, 'save', NULL, 'draft',",
            f"       jsonb_build_object('lines', (SELECT count(*) FROM lines), 'source', 'sql_import')",
            "FROM inv;",
            "",
        ]
    assert grand == GRAND_TOTAL
    assert sum(Decimal(a) for _n, _d, a in VOUCHERS) == GRAND_TOTAL
    voucher_rows = ",\n".join(
        f"    ({lit(number)}, DATE {lit(day)}, {Decimal(amount):.2f}, {lit(purpose)})"
        for (number, day, amount), purpose in zip(VOUCHERS, voucher_purposes(totals))
    )
    out += [
        f"-- Receipt vouchers ({VOUCHER_PAYMENT_TYPE}), total {GRAND_TOTAL}.",
        "INSERT INTO receipt_vouchers (",
        "    voucher_number, voucher_date, customer_id, company_id, payment_type, amount, description)",
        f"SELECT v.number, v.day, {customer_id}, {seller_id}, {lit(VOUCHER_PAYMENT_TYPE)}, v.amount, v.purpose",
        "FROM (VALUES",
        voucher_rows,
        ") AS v(number, day, amount, purpose);",
        "",
        "COMMIT;",
        "",
    ]
    with open(os.path.join(HERE, "barakah_invoices.sql"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(out))


if __name__ == "__main__":
    main()
