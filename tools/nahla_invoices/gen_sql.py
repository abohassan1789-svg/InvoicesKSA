"""Generate ``nahla_invoices.sql``: the 7 «نهلة الخليج» sales invoices for
مؤسسة صرح الرفاع التجارية as draft rows in the app's own tables.

Line amounts are computed with the app's own rules
(``SaudiSalesInvoiceService.compute_line_amounts`` / ``compute_totals``, copied
here as plain Decimal math so the script needs no app imports), and each
invoice's totals are asserted against the Excel figures before anything is
written. ``alloc.json`` holds the free-text lines of each invoice, taken from
the «نواقص» quotation.

Run:  python tools/nahla_invoices/gen_sql.py
"""

from __future__ import annotations

import json
import os
from decimal import ROUND_HALF_UP, Decimal

HERE = os.path.dirname(os.path.abspath(__file__))

SELLER = {
    "name_ar": "شركة نهلة الخليج التجارية",
    "name_en": "NAHLA AL KHALEEJ TRADING COMPANY",
    "cr": "2050174334",
    "vat": "311848109200003",
    "address_ar": "المملكة العربية السعودية - 32427 - الدمام - حي العنود",
    "address_en": "Al-Onud District - Dammam - 32427 - Kingdom of Saudi Arabia",
}
CUSTOMER = {
    "name": "مؤسسة صرح الرفاع التجارية",
    "vat": "310160803100003",
    "address": "الدمام،العامه،11،3241",
}
# (invoice number, issue date, pre-tax amount) — exactly as in the Excel sheet.
INVOICES = [
    ("4487", "2026-07-04", 14500),
    ("4502", "2026-07-16", 16200),
    ("4518", "2026-08-05", 11300),
    ("4529", "2026-08-13", 12700),
    ("4543", "2026-08-26", 15000),
    ("4567", "2026-09-08", 18800),
    ("4585", "2026-09-23", 13500),
]
VAT_RATE = Decimal("15.00")
CENT = Decimal("0.01")


def money(value: Decimal) -> Decimal:
    return value.quantize(CENT, rounding=ROUND_HALF_UP)


def lit(value: object) -> str:
    """SQL literal (strings quoted and escaped; None -> NULL)."""
    if value is None:
        return "NULL"
    if isinstance(value, Decimal):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def main() -> None:
    alloc = json.load(open(os.path.join(HERE, "alloc.json"), encoding="utf-8"))
    numbers = ", ".join(lit(n) for n, _d, _a in INVOICES)
    out: list[str] = [
        "-- «نهلة الخليج» → مؤسسة صرح الرفاع التجارية: 7 sales invoices (drafts).",
        "-- Generated by tools/nahla_invoices/gen_sql.py — do not edit by hand.",
        "-- Safe to run once: the whole script is one transaction and it stops",
        "-- without changing anything if any of these invoice numbers already",
        "-- exists for this seller.",
        "",
        "BEGIN;",
        "",
        "-- Seller (matched by VAT number; inserted only if missing).",
        "INSERT INTO companies (name_ar, name_en, commercial_registration, vat_number, address_ar, address_en)",
        f"SELECT {lit(SELLER['name_ar'])}, {lit(SELLER['name_en'])}, {lit(SELLER['cr'])}, {lit(SELLER['vat'])},",
        f"       {lit(SELLER['address_ar'])}, {lit(SELLER['address_en'])}",
        f"WHERE NOT EXISTS (SELECT 1 FROM companies WHERE vat_number = {lit(SELLER['vat'])});",
        "",
        "-- Customer (matched by VAT number; inserted only if missing).",
        "INSERT INTO customers (customer_name, vat_number, address)",
        f"SELECT {lit(CUSTOMER['name'])}, {lit(CUSTOMER['vat'])}, {lit(CUSTOMER['address'])}",
        f"WHERE NOT EXISTS (SELECT 1 FROM customers WHERE vat_number = {lit(CUSTOMER['vat'])});",
        "",
        "DO $$",
        "BEGIN",
        "    IF EXISTS (",
        "        SELECT 1 FROM sales_invoices i",
        "        JOIN companies c ON c.id = i.seller_company_id",
        f"        WHERE c.vat_number = {lit(SELLER['vat'])} AND i.invoice_number IN ({numbers})",
        "    ) THEN",
        "        RAISE EXCEPTION 'نهلة الخليج: invoice numbers 4487-4585 already exist; nothing was imported.';",
        "    END IF;",
        "END $$;",
        "",
    ]
    seller_id = f"(SELECT id FROM companies WHERE vat_number = {lit(SELLER['vat'])})"
    customer_id = (
        f"(SELECT MIN(customer_id) FROM customers WHERE vat_number = {lit(CUSTOMER['vat'])})"
    )
    grand = Decimal(0)
    for (number, day, amount), lines in zip(INVOICES, alloc):
        rows = []
        subtotal = vat_total = Decimal(0)
        for ln in lines:
            qty, price = Decimal(ln["qty"]), Decimal(ln["price"])
            before = money(qty * price)
            vat = money(before * VAT_RATE / 100)
            subtotal += before
            vat_total += vat
            rows.append((ln["code"], ln["name"], qty, price, before, vat, before + vat))
        subtotal, vat_total = money(subtotal), money(vat_total)
        total = subtotal + vat_total
        assert subtotal == amount and vat_total == money(Decimal(amount) * VAT_RATE / 100), number
        grand += total
        values = ",\n".join(
            f"    ({n}, {lit(code)}, {lit(name)}, {qty}, {price}, {before}, {vat}, {tot})"
            for n, (code, name, qty, price, before, vat, tot) in enumerate(rows, start=1)
        )
        out += [
            f"-- Invoice {number} — {day} — {subtotal} + VAT {vat_total} = {total}",
            "WITH inv AS (",
            "    INSERT INTO sales_invoices (",
            "        invoice_number, issue_datetime, seller_company_id, seller_name_ar_snapshot,",
            "        seller_name_en_snapshot, seller_vat_number_snapshot, customer_id,",
            "        customer_name_snapshot, customer_vat_number_snapshot, customer_address_snapshot,",
            "        payment_type, invoice_currency_code, tax_currency_code, subtotal_before_vat,",
            "        invoice_discount_rate, invoice_discount_amount, subtotal_after_discount,",
            "        vat_total, total_including_vat, document_status)",
            f"    VALUES ({lit(number)}, {lit(day + ' 12:00:00+03')}, {seller_id},",
            f"        {lit(SELLER['name_ar'])}, {lit(SELLER['name_en'])}, {lit(SELLER['vat'])},",
            f"        {customer_id}, {lit(CUSTOMER['name'])}, {lit(CUSTOMER['vat'])}, {lit(CUSTOMER['address'])},",
            f"        'cash', 'SAR', 'SAR', {subtotal}, 0, 0, {subtotal}, {vat_total}, {total}, 'draft')",
            "    RETURNING id, invoice_number, seller_company_id",
            "), lines AS (",
            "    INSERT INTO sales_invoice_lines (",
            "        invoice_id, line_number, product_id, product_code_snapshot, product_name_snapshot,",
            "        unit_code, quantity, unit_price, line_amount_before_vat, vat_category_code,",
            "        vat_rate, vat_amount, line_total_including_vat)",
            "    SELECT inv.id, v.n, NULL, v.code, v.name, 'PCE', v.qty, v.price, v.before, 'S',",
            "           15.00, v.vat, v.total",
            "    FROM inv, (VALUES",
            values,
            "    ) AS v(n, code, name, qty, price, before, vat, total)",
            "    RETURNING 1",
            ")",
            "INSERT INTO sales_invoice_audit_logs (",
            "    invoice_id, invoice_number_snapshot, seller_company_id_snapshot, action,",
            "    old_status, new_status, details)",
            "SELECT inv.id, inv.invoice_number, inv.seller_company_id, 'save', NULL, 'draft',",
            f"       jsonb_build_object('lines', (SELECT count(*) FROM lines), 'source', 'sql_import')",
            "FROM inv;",
            "",
        ]
    assert grand == Decimal("117300.00")
    out += ["COMMIT;", ""]
    with open(os.path.join(HERE, "nahla_invoices.sql"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(out))


if __name__ == "__main__":
    main()
